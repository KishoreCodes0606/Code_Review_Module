import React, { useState } from 'react';
import { AlertTriangle, CheckCircle2, Download, FileJson, FileText, Loader2 } from 'lucide-react';
import { reportDownloadUrl } from '../../utils/analysisApi';

/**
 * M3 report export.
 *
 * Both buttons download the bytes the backend generated from this run
 * (findings, remediation, PR summary, health) - never client-side content.
 *
 *  - PDF: the endpoint replies with `Content-Disposition: attachment`, so a real
 *    anchor click lets the browser save it.
 *  - JSON: the endpoint replies with a JSON envelope (status/run_id/filename/report),
 *    which the browser would DISPLAY rather than download. It is therefore
 *    fetched and saved as a Blob using the backend's own filename, so clicking
 *    JSON never navigates away from the workspace.
 */
export function ReportExportBar({ runId, runStatus, disabled }) {
  const [busy, setBusy] = useState(false);
  const [done, setDone] = useState(null);
  const [error, setError] = useState('');

  if (!runId) return null;

  const saveBlob = (blob, filename) => {
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement('a');
    anchor.href = url;
    anchor.download = filename;
    document.body.appendChild(anchor);
    anchor.click();
    anchor.remove();
    // Revoke on a later tick so the click has been handed to the browser.
    setTimeout(() => URL.revokeObjectURL(url), 2000);
  };

  const downloadPdf = () => {
    setError('');
    setDone('pdf');
    const anchor = document.createElement('a');
    anchor.href = reportDownloadUrl(runId, 'pdf');
    anchor.rel = 'noopener';
    anchor.download = '';
    document.body.appendChild(anchor);
    anchor.click();
    anchor.remove();
  };

  const downloadJson = async () => {
    setError('');
    setDone(null);
    setBusy(true);
    try {
      const res = await fetch(reportDownloadUrl(runId, 'json'));
      if (!res.ok) {
        let detail = `HTTP ${res.status}`;
        try {
          const body = await res.json();
          detail = body?.message || body?.error || detail;
        } catch {
          /* non-JSON error body - keep the status text */
        }
        throw new Error(detail);
      }
      const envelope = await res.json();
      const report = envelope?.report ?? envelope;
      const blob = new Blob([JSON.stringify(report, null, 2)], { type: 'application/json' });
      saveBlob(blob, envelope?.filename || `code-review-${runId}.json`);
      setDone('json');
    } catch (err) {
      setError(`JSON export failed: ${err?.message || String(err)}`);
    } finally {
      setBusy(false);
    }
  };

  return (
    <section
      aria-label="Report export"
      className="rounded-xl border border-slate-800 bg-slate-900/60 p-3 flex flex-wrap items-center justify-between gap-2"
    >
      <div className="min-w-0">
        <span className="text-xs font-semibold uppercase tracking-wider text-slate-400 flex items-center gap-1.5">
          <Download className="w-3.5 h-3.5 text-indigo-400" /> Export report
        </span>
        <p className="text-[10px] text-slate-500">
          Generated by the backend from this run's real findings, remediation and summary
          {runStatus && runStatus !== 'COMPLETED' ? ` - the report is marked ${runStatus}` : ''}.
        </p>
      </div>

      <div className="flex items-center gap-2">
        <button
          type="button"
          onClick={downloadPdf}
          disabled={disabled || busy}
          className="inline-flex items-center gap-1.5 px-3 py-2 rounded-lg bg-rose-600 hover:bg-rose-500 disabled:bg-slate-800 disabled:text-slate-500 text-white text-xs font-semibold transition-colors"
        >
          {busy ? <Loader2 className="w-3.5 h-3.5 animate-spin" /> : <FileText className="w-3.5 h-3.5" />}
          PDF
        </button>
        <button
          type="button"
          onClick={downloadJson}
          disabled={disabled || busy}
          className="inline-flex items-center gap-1.5 px-3 py-2 rounded-lg bg-slate-800 hover:bg-slate-700 disabled:text-slate-500 text-slate-100 text-xs font-semibold transition-colors"
        >
          {busy ? <Loader2 className="w-3.5 h-3.5 animate-spin" /> : <FileJson className="w-3.5 h-3.5" />}
          JSON
        </button>
      </div>

      {done && (
        <span className="w-full text-[10px] text-emerald-300 flex items-center gap-1.5">
          <CheckCircle2 className="w-3 h-3" />
          {done.toUpperCase()} report generated by the backend and saved - check your browser downloads.
        </span>
      )}
      {error && (
        <span className="w-full text-[10px] text-rose-300 flex items-center gap-1.5">
          <AlertTriangle className="w-3 h-3" /> {error}
        </span>
      )}
    </section>
  );
}

export default ReportExportBar;
